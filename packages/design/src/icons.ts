export interface Pixel {
  x: number;
  y: number;
  color: string;
}

/** Expand an icon into opaque pixels. `tint` fills the 'o' cells. */
export function iconPixels(name: IconName, tint: string = p.ink): Pixel[] {
  const out: Pixel[] = [];
  ICONS[name].forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x] as string;
      if (ch === '.') continue;
      out.push({ x, y, color: ch === 'o' ? tint : (INK_MAP[ch] ?? p.ink) });
    }
  });
  return out;
}

export function iconSize(name: IconName): { w: number; h: number } {
  const rows = ICONS[name];
  return { w: rows[0]?.length ?? 0, h: rows.length };
}
